def build_member_system_prompt(*, mode: str, role: CouncilRole) -> str:
    return "\n\n".join(
        (
            get_system_prompt(mode),
            ROLE_PROMPTS[role],
            (
                "Сформируй самостоятельный ответ. Не пытайся угадать мнения "
                "других участников Совета."
            ),
        )
    )

